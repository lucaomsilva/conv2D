#!/usr/bin/env python3
"""Make docs/report/ap2/resume.md: AP2 tables (data only, no deep analysis).

Use: python3 scripts/analysis/ap2_compare.py
Run scripts/compile_data.py first.
"""
import os

from common import REPORT_AP2, SIZES, load_ap2

MAIN = ("p-ht-e", "static")


def rows(d, n, places, schedule):
    r = [x for x in d if x["binary_name"] == "parallel_omp" and x["matrix_size"] == n
         and x["places"] == places and x["schedule"] == schedule]
    return sorted(r, key=lambda x: x["threads"])


def ref(d, n, binary="simd_aligned"):
    r = [x for x in d if x["binary_name"] == binary and x["matrix_size"] == n]
    return r[0] if r else None


def f(v, fmt):
    return format(v, fmt) if v is not None else "-"


def threads_table(d, n):
    base = ref(d, n)
    out = ["| T | Time (ms) | Speedup T1 | Efficiency | Speedup AP1 | MFLOPS | Power (W) | "
           "Energy (mJ) | MFLOPS/W | L1 miss | L2 miss | L3 miss |",
           "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rows(d, n, *MAIN):
        t = r["execution_time_s_median"]
        ap1 = base["execution_time_s_median"] / t if base and t else None
        e = r["energy_joules_median"]
        out.append(
            f"| {int(r['threads'])} | {f(t * 1e3, '.3f')} | {f(r['speedup_vs_t1'], '.2f')} | "
            f"{f(r['parallel_efficiency'], '.2f')} | {f(ap1, '.2f')} | "
            f"{f(r['mflops_median'], '.0f')} | {f(r['power_watts_median'], '.2f')} | "
            f"{f(e and e * 1e3, '.3f')} | {f(r['mflops_per_watt_median'], '.0f')} | "
            f"{f(r['l1_misses_median'], '.3g')} | {f(r['l2_misses_median'], '.3g')} | "
            f"{f(r['l3_misses_median'], '.3g')} |")
    return "\n".join(out) + "\n"


def best_table(d, n):
    """AP1 best (simd_aligned), OpenCV and best OpenMP by time and by MFLOPS/W."""
    base = ref(d, n)
    omp = [x for x in d if x["binary_name"] == "parallel_omp" and x["matrix_size"] == n]
    if not base or not omp:
        return "No data.\n"
    fast = min(omp, key=lambda x: x["execution_time_s_median"])
    eff = max(omp, key=lambda x: x["mflops_per_watt_median"] or 0)
    out = ["| Version | Time (ms) | Speedup | Power (W) | Energy (mJ) | MFLOPS/W |",
           "|---|---:|---:|---:|---:|---:|"]
    cv = ref(d, n, "library_o3")
    for name, r in [("simd_aligned (AP1, 1 thread)", base),
                    ("OpenCV filter2D (1 thread)", cv),
                    (f"OpenMP fastest: T={int(fast['threads'])} {fast['places']} {fast['schedule']}", fast),
                    (f"OpenMP best MFLOPS/W: T={int(eff['threads'])} {eff['places']} {eff['schedule']}", eff)]:
        if r is None:
            continue
        t = r["execution_time_s_median"]
        out.append(f"| {name} | {t * 1e3:.3f} | {base['execution_time_s_median'] / t:.2f}x | "
                   f"{f(r['power_watts_median'], '.2f')} | "
                   f"{f(r['energy_joules_median'] and r['energy_joules_median'] * 1e3, '.3f')} | "
                   f"{f(r['mflops_per_watt_median'], '.0f')} |")
    return "\n".join(out) + "\n"


def variant_table(d, n, field, values, fixed):
    """Time (ms) per thread count, one column per placement or schedule."""
    cols = {}
    for v in values:
        key = (v, fixed) if field == "places" else (fixed, v)
        cols[v] = {int(r["threads"]): r["execution_time_s_median"] for r in rows(d, n, *key)}
    ts = sorted({t for c in cols.values() for t in c})
    if not ts:
        return "No data.\n"
    out = ["| T | " + " | ".join(values) + " |", "|---:|" + "---:|" * len(values)]
    for t in ts:
        out.append(f"| {t} | " + " | ".join(f(cols[v].get(t) and cols[v][t] * 1e3, '.3f')
                                            for v in values) + " |")
    return "\n".join(out) + "\n"


def main():
    d = load_ap2()
    places = sorted({x["places"] for x in d if x["places"]})
    scheds = sorted({x["schedule"] for x in d if x["schedule"]})
    out = ["# AP2 result summary\n",
           "Data only. Values are the median of 10 runs.",
           "Speedup T1 = time(1 thread) / time(T), same placement and schedule. "
           "Efficiency = Speedup T1 / T.",
           "Speedup AP1 = time(simd_aligned, measured in the same session) / time(T).",
           "OpenCV filter2D does not scale with threads in this build (TBB, no IPP); it runs with 1 thread.",
           "Misses are per kernel call (sum of P-cores and E-cores).",
           "Source: `docs/data/compiled/summary.csv`. Generated by "
           "`scripts/analysis/ap2_compare.py`.\n"]
    for n in SIZES:
        out += [f"## N = {n}\n",
                "### AP1 best x OpenMP\n", best_table(d, n),
                f"### Threads ({MAIN[0]}, {MAIN[1]})\n", threads_table(d, n),
                "### Placement (static), time (ms)\n",
                variant_table(d, n, "places", places, "static"),
                "### Schedule (p-ht-e), time (ms)\n",
                variant_table(d, n, "schedule", scheds, "p-ht-e")]
    os.makedirs(REPORT_AP2, exist_ok=True)
    path = os.path.join(REPORT_AP2, "resume.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out))
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
