#!/usr/bin/env python3
"""Make docs/report/ap1/resume.md: comparison tables (data only, no deep analysis).

Use: python3 scripts/analysis/compare.py
Run scripts/compile_data.py first.
"""
import os

from common import REPORT, SIZES, best_block, get, label, load

H = "| Implementation | Time (ms) | MFLOPS | Power (W) | Energy (J) | MFLOPS/W | Speedup |"
SEP = "|---|---:|---:|---:|---:|---:|---:|"


def line(row, name, ref):
    t = row["execution_time_s_median"]
    return (f"| {name} | {t * 1e3:.3f} | {row['mflops_median']:.0f} | "
            f"{row['power_watts_median']:.2f} | {row['energy_joules_median']:.3f} | "
            f"{row['mflops_per_watt_median']:.2f} | "
            f"{ref['execution_time_s_median'] / t:.2f}x |")


def table(rows, ref):
    return "\n".join([H, SEP] + [line(r, n, ref) for n, r in rows]) + "\n"


def pct(a, b):
    return f"{(a - b) / b * 100:+.1f}%"


def main():
    d = load()
    out = ["# Result summary\n",
           "Data only. Values are the median of 10 runs.",
           "Speedup is time(reference) / time(version). The reference is shown in each table.",
           "Source: `docs/data/compiled/summary.csv`. Generated by "
           "`scripts/analysis/compare.py`.\n"]

    for n in SIZES:
        base = get(d, "baseline_o3", n)
        bs = best_block(d, "blocking_seq", n)
        bm = best_block(d, "blocking_simd", n)
        out.append(f"\n## N = {n} (reference: Base -O3 row)\n")
        rows = [
            ("Base -O0 row", get(d, "baseline_no_o3", n)),
            ("Base -O0 col", get(d, "baseline_no_o3", n, "col")),
            ("Base -O3 row", base),
            ("Base -O3 col", get(d, "baseline_o3", n, "col")),
            (label("simd_autovec", "row"), get(d, "simd_autovec", n)),
            (label("simd_unaligned", "row"), get(d, "simd_unaligned", n)),
            (label("simd_aligned", "row"), get(d, "simd_aligned", n)),
            (label("blocking_seq", "", int(bs["block_size"])), bs),
            (label("blocking_simd", "", int(bm["block_size"])), bm),
            (label("library_o3", "row"), get(d, "library_o3", n)),
        ]
        out.append(table(rows, base))

        out.append(f"\n### Tiling block size, N = {n}\n")
        brows = []
        for b in (8, 16, 32, 64):
            brows.append((f"Tiling B={b}", get(d, "blocking_seq", n, f"block_{b}", b)))
        for b in (8, 16, 32, 64):
            brows.append((f"Tiling+SIMD B={b}", get(d, "blocking_simd", n, f"block_{b}", b)))
        out.append(table(brows, base))

    out.append("\n## Isolated effects (change against the stated reference)\n")
    out.append("| N | Effect | Time | Power | Energy |")
    out.append("|---:|---|---:|---:|---:|")
    for n in SIZES:
        g = lambda b, m="row": get(d, b, n, m)
        bs, bm = best_block(d, "blocking_seq", n), best_block(d, "blocking_simd", n)
        pairs = [
            ("Cache affinity (-O3): row vs col", g("baseline_o3"), g("baseline_o3", "col")),
            ("Cache affinity (-O0): row vs col", g("baseline_no_o3"), g("baseline_no_o3", "col")),
            ("Vectorization: SIMD pragma+aligned vs Base -O3 row", g("simd_aligned"), g("baseline_o3")),
            ("Tiling only (best B) vs Base -O3 row", bs, g("baseline_o3")),
            (f"Combined (B={int(bm['block_size'])}) vs Base -O3 row", bm, g("baseline_o3")),
            (f"Combined (B={int(bm['block_size'])}) vs SIMD pragma+aligned", bm, g("simd_aligned")),
            ("OpenCV vs SIMD pragma+aligned", g("library_o3"), g("simd_aligned")),
        ]
        for name, a, b in pairs:
            out.append(
                f"| {n} | {name} | {pct(a['execution_time_s_median'], b['execution_time_s_median'])} | "
                f"{pct(a['power_watts_median'], b['power_watts_median'])} | "
                f"{pct(a['energy_joules_median'], b['energy_joules_median'])} |")
    out.append("\nNegative time or energy means the first version is better.\n")

    os.makedirs(REPORT, exist_ok=True)
    path = os.path.join(REPORT, "resume.md")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"Written: {path}")


if __name__ == "__main__":
    main()
